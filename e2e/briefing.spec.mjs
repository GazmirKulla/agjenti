test('desktop: verified metrics, manual refresh, navigation preserves draft and creates no conversation', async ({ page }) => {
  const before = count(), posts = [], reads = [];
  page.on('request', r => { if (r.url().includes('/api/business-assistant')) { if (r.method() === 'POST') posts.push(r.url()); if (r.url().includes('/briefing?')) reads.push(r.url()); } });
  await login(page);
  await expect(card(page).locator('.briefing-metrics > div')).toHaveCount(4);
  await expect(card(page).getByText('Mesazhe hyrëse').locator('..').locator('..').locator('dd')).toHaveText('2');
  await expect(card(page).getByText('Porosi të krijuara').locator('..').locator('..').locator('dd')).toHaveText('3');
  await page.screenshot({ path: `${work}/briefing-desktop.png` });
  await page.locator('#business-assistant-input').fill('Drafti im i papërfunduar');
  const readCount = reads.length;
  await card(page).getByRole('link', { name: /Porosi të krijuara/ }).click();
  await expect(page).toHaveURL(`http://localhost:3103${base}/orders`);
  await page.getByRole('navigation', { name: 'Menuja e biznesit', exact: true }).getByRole('link', { name: 'Asistenti AI', exact: true }).click();
  await expect(card(page)).toBeVisible();
  await expect(page.locator('#business-assistant-input')).toHaveValue('Drafti im i papërfunduar');
  expect(reads.length).toBe(readCount);
  sql(`insert into public.messages(business_id,conversation_id,direction,source) values('${id}','${conversation}','inbound','customer');`);
  await card(page).getByRole('button', { name: 'Rifresko përmbledhjen' }).click();
  await expect(card(page).getByText('Mesazhe hyrëse').locator('..').locator('..').locator('dd')).toHaveText('3');
  expect(count()).toBe(before);
  expect(posts).toEqual([]);
});
